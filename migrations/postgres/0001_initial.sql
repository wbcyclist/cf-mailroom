-- Fresh PostgreSQL schema. Legacy SQLite migrations in the parent directory are not applied.

CREATE TABLE mailboxes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  address TEXT NOT NULL CHECK (address = lower(address)) UNIQUE,
  display_name TEXT,
  color TEXT NOT NULL DEFAULT '#6366f1',
  agent_mode TEXT NOT NULL DEFAULT 'off' CHECK (agent_mode IN ('off', 'draft', 'auto')),
  agent_instructions TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  domain_id BIGINT
);

CREATE TABLE stored_files (
  key TEXT PRIMARY KEY,
  mailbox_id BIGINT NOT NULL REFERENCES mailboxes(id) ON DELETE CASCADE,
  content BYTEA NOT NULL CHECK (octet_length(content) <= 26214400),
  content_type TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_stored_files_mailbox ON stored_files(mailbox_id);

CREATE TABLE threads (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mailbox_id BIGINT NOT NULL REFERENCES mailboxes(id) ON DELETE CASCADE,
  subject TEXT NOT NULL DEFAULT '',
  normalized_subject TEXT NOT NULL DEFAULT '',
  snippet TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'archived', 'needs_human')),
  is_read BIGINT NOT NULL DEFAULT 0,
  message_count BIGINT NOT NULL DEFAULT 0,
  last_message_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_threads_mailbox ON threads(mailbox_id, status, last_message_at DESC);

CREATE INDEX idx_threads_status ON threads(status, last_message_at DESC);

CREATE INDEX idx_threads_subject ON threads(mailbox_id, normalized_subject);

CREATE TABLE messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  thread_id BIGINT NOT NULL REFERENCES threads(id) ON DELETE CASCADE,

  message_id TEXT NOT NULL UNIQUE,
  in_reply_to TEXT,
  references_ids TEXT NOT NULL DEFAULT '[]',
  direction TEXT NOT NULL CHECK (direction IN ('inbound', 'outbound')),
  sent_by TEXT NOT NULL DEFAULT 'external' CHECK (sent_by IN ('external', 'human', 'agent')),
  from_address TEXT NOT NULL,
  from_name TEXT,
  to_addresses TEXT NOT NULL DEFAULT '[]',
  cc_addresses TEXT NOT NULL DEFAULT '[]',
  subject TEXT NOT NULL DEFAULT '',
  text_body TEXT,
  html_body TEXT,

  raw_key TEXT REFERENCES stored_files(key),

  is_auto_submitted BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  reply_to_addresses TEXT NOT NULL DEFAULT '[]'
);

CREATE INDEX idx_messages_thread ON messages(thread_id, created_at);

CREATE TABLE drafts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  thread_id BIGINT NOT NULL REFERENCES threads(id) ON DELETE CASCADE,
  text_body TEXT NOT NULL,
  created_by TEXT NOT NULL DEFAULT 'human' CHECK (created_by IN ('human', 'agent')),

  agent_notes TEXT,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'sent', 'discarded')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  playbook_id BIGINT,
  source_inbound_message_id BIGINT
);

CREATE INDEX idx_drafts_thread ON drafts(thread_id, status);

CREATE TABLE playbooks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mailbox_id BIGINT NOT NULL REFERENCES mailboxes(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  when_to_use TEXT NOT NULL,
  instructions TEXT NOT NULL,
  example_reply TEXT,
  enabled BIGINT NOT NULL DEFAULT 1 CHECK (enabled IN (0, 1)),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_playbooks_mailbox ON playbooks(mailbox_id, enabled, updated_at DESC);

CREATE INDEX idx_drafts_playbook ON drafts(playbook_id);

CREATE TABLE domains (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL CHECK (name = lower(name)) UNIQUE,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'active')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  activated_at TIMESTAMPTZ
);

CREATE INDEX idx_mailboxes_domain ON mailboxes(domain_id, address);

CREATE TABLE attachments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id BIGINT NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
  filename TEXT,
  content_type TEXT NOT NULL,
  size BIGINT NOT NULL,
  disposition TEXT CHECK (disposition IN ('attachment', 'inline')),
  content_id TEXT,
  file_key TEXT NOT NULL UNIQUE REFERENCES stored_files(key),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_attachments_message ON attachments(message_id, id);

CREATE TABLE draft_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  thread_id BIGINT NOT NULL REFERENCES threads(id) ON DELETE CASCADE,
  inbound_message_id BIGINT NOT NULL UNIQUE REFERENCES messages(id) ON DELETE CASCADE,
  status TEXT NOT NULL DEFAULT 'queued'
    CHECK (status IN ('queued', 'generating', 'ready', 'failed', 'superseded')),
  attempt_count BIGINT NOT NULL DEFAULT 0,
  draft_id BIGINT REFERENCES drafts(id) ON DELETE SET NULL,
  error TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  started_at TIMESTAMPTZ,
  finished_at TIMESTAMPTZ
);

CREATE INDEX idx_draft_runs_thread ON draft_runs(thread_id, created_at DESC);

CREATE INDEX idx_draft_runs_status ON draft_runs(status, created_at);

CREATE TABLE reply_attempts (
  id TEXT PRIMARY KEY,
  thread_id BIGINT NOT NULL REFERENCES threads(id) ON DELETE CASCADE,
  draft_id BIGINT REFERENCES drafts(id) ON DELETE SET NULL,
  status TEXT NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'sending', 'sent', 'failed')),
  text_body TEXT NOT NULL,
  to_addresses TEXT NOT NULL,
  message_id TEXT UNIQUE,
  error TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  inbound_message_id BIGINT REFERENCES messages(id) ON DELETE RESTRICT,
  sent_by TEXT NOT NULL DEFAULT 'human'
  CHECK (sent_by IN ('human', 'agent')),
  actor_id TEXT,
  oauth_client_id TEXT,
  attachments TEXT NOT NULL DEFAULT '[]'
);

CREATE INDEX idx_reply_attempts_thread ON reply_attempts(thread_id, created_at DESC);

CREATE INDEX idx_drafts_source_message ON drafts(source_inbound_message_id, status);

CREATE INDEX idx_reply_attempts_inbound_message ON reply_attempts(inbound_message_id);

CREATE TABLE global_settings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id = 1),
  browser_notifications_enabled BIGINT NOT NULL DEFAULT 0
    CHECK (browser_notifications_enabled IN (0, 1)),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  ai_model TEXT
);

CREATE TABLE push_subscriptions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  endpoint TEXT NOT NULL UNIQUE,
  expiration_time BIGINT,
  p256dh TEXT NOT NULL,
  auth TEXT NOT NULL,
  user_agent TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_push_subscriptions_updated ON push_subscriptions(updated_at DESC);

CREATE TABLE outbound_attempts (
  id TEXT PRIMARY KEY,
  mailbox_id BIGINT NOT NULL REFERENCES mailboxes(id) ON DELETE RESTRICT,
  thread_id BIGINT REFERENCES threads(id) ON DELETE RESTRICT,
  status TEXT NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'sending', 'sent', 'failed')),
  to_addresses TEXT NOT NULL,
  subject TEXT NOT NULL,
  text_body TEXT NOT NULL,
  message_id TEXT UNIQUE,
  actor_id TEXT,
  oauth_client_id TEXT,
  error TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  attachments TEXT NOT NULL DEFAULT '[]',
  sent_by TEXT NOT NULL DEFAULT 'agent'
  CHECK (sent_by IN ('human', 'agent'))
);

CREATE INDEX idx_outbound_attempts_mailbox
  ON outbound_attempts(mailbox_id, created_at DESC);

CREATE INDEX idx_outbound_attempts_thread
  ON outbound_attempts(thread_id, created_at DESC);

CREATE TABLE mcp_send_budget (
  actor_id TEXT NOT NULL,
  budget_date TEXT NOT NULL,
  send_count BIGINT NOT NULL DEFAULT 0 CHECK (send_count >= 0),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (actor_id, budget_date)
);

CREATE TABLE oauth_authorization_transactions (
  token_hash TEXT PRIMARY KEY CHECK (length(token_hash) = 64),
  owner_sub TEXT NOT NULL,
  auth_request_json TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL,
  consumed_at BIGINT,
  CHECK (expires_at > created_at),
  CHECK (consumed_at IS NULL OR consumed_at >= created_at)
);

CREATE INDEX idx_oauth_authorization_transactions_expiry
  ON oauth_authorization_transactions(expires_at);

CREATE TABLE labels (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mailbox_id BIGINT NOT NULL REFERENCES mailboxes(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  condition TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX idx_labels_mailbox_name ON labels(mailbox_id, lower(name));

CREATE TABLE thread_labels (
  thread_id BIGINT NOT NULL REFERENCES threads(id) ON DELETE CASCADE,
  label_id BIGINT NOT NULL REFERENCES labels(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (thread_id, label_id)
);

CREATE INDEX idx_thread_labels_label ON thread_labels(label_id, thread_id);

ALTER TABLE mailboxes ADD FOREIGN KEY (domain_id) REFERENCES domains(id) ON DELETE RESTRICT;
ALTER TABLE drafts ADD FOREIGN KEY (playbook_id) REFERENCES playbooks(id) ON DELETE SET NULL;
ALTER TABLE drafts ADD FOREIGN KEY (source_inbound_message_id) REFERENCES messages(id) ON DELETE SET NULL;
ALTER TABLE messages ADD COLUMN search_document TSVECTOR GENERATED ALWAYS AS (
  to_tsvector('simple', coalesce(subject, '') || ' ' || left(coalesce(text_body, ''), 20000))
) STORED;
CREATE INDEX idx_messages_search ON messages USING GIN(search_document);
